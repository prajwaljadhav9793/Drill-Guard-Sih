function buildOffsetFormations(offsetShiftM: number): FormationInterval[] {
  return BASE_FORMATIONS.map((f, idx) => {
    const topMD = idx === 0 ? 0 : Math.max(100, f.topMD + offsetShiftM);
    const bottomMD = f.bottomMD + offsetShiftM;
    return {
      ...f,
      topMD,
      bottomMD,
      topTVD: Math.round(topMD * 0.978),
      bottomTVD: Math.round(bottomMD * 0.978),
    };
  });
}

function generateDepthCurve(td: number, seed: number): DepthParameterPoint[] {
  const points: DepthParameterPoint[] = [];
  const step = 200;
  for (let d = 200; d <= td; d += step) {
    const progress = d / td;
    const wave = Math.sin(d / 350 + seed);
    const rop = Number(Math.max(6.5, 29 - progress * 15 + wave * 3.2).toFixed(1));
    const wob = Number((8 + progress * 11 + Math.cos(d / 400 + seed) * 1.8).toFixed(1));
    const rpm = Math.round(140 - progress * 25 + wave * 8);
    const torque = Number((5.2 + progress * 9.5 + (d > 2750 && d < 3050 ? 2.6 : 0) + wave * 1.1).toFixed(1));
    const spp = Math.round(1650 + progress * 1150 + wave * 85);
    const flowRate = Math.round(2100 - progress * 580);
    const mudWeight = Number((1.05 + progress * 0.24 + (d > 3040 ? 0.06 : 0)).toFixed(2));
    const ecd = Number((mudWeight + 0.05 + (progress * 0.02)).toFixed(2));
    const hookLoad = Number((68 + progress * 64).toFixed(1));
    const days = Number(((d / td) * (32 + (seed % 9))).toFixed(1));
    points.push({
      depthMD: d,
      depthTVD: Math.round(d * 0.978),
      days,
      rop,
      wob,
      rpm,
      torque,
      spp,
      flowRate,
      mudWeight,
      ecd,
      hookLoad,
    });
  }
  return points;
}

